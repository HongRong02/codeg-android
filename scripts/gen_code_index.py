#!/usr/bin/env python3
"""Generate a declaration index of the Kotlin sources for task scoping.

Writes one Markdown file per package directory under
.taskmaster/docs/code-index/, listing every class/object/interface/fun/val
declaration with its line number and full (whitespace-collapsed) signature,
so an agent can jump straight to `path:line` instead of reading whole files.

Usage: python scripts/gen_code_index.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "app/src/main/java/app/codeg/android"
OUT = ROOT / ".taskmaster/docs/code-index"

MODIFIERS = (
    r"(?:(?:public|private|internal|protected|override|open|abstract|sealed|data|"
    r"enum|inline|value|suspend|operator|infix|tailrec|const|lateinit|companion|"
    r"inner|annotation|fun\s+interface|expect|actual)\s+)*"
)
DECL = re.compile(
    r"^(?P<indent>[ \t]*)" + MODIFIERS
    + r"(?P<kind>class|object|interface|fun|val|var|typealias)\b"
)
# Only index declarations at file or class-member level, not locals in bodies.
MAX_INDENT = 8


def signature(lines: list[str], start: int) -> str:
    """Join a declaration's lines until its parentheses close and a body/
    initializer/end is reached; drop the body itself."""
    parts, depth = [], 0
    for i in range(start, min(start + 40, len(lines))):
        line = lines[i].split("//")[0].rstrip()
        cut = None
        for j, ch in enumerate(line):
            if ch in "(<[":
                depth += 1
            elif ch in ")]" or (ch == ">" and line[j - 1 : j] != "-"):
                depth = max(0, depth - 1)
            elif depth == 0 and ch == "{":
                cut = j
                break
            elif depth == 0 and ch == "=" and line[j + 1 : j + 2] not in ("=", ">") and line[j - 1 : j] not in ("!", "<", ">", "="):
                cut = j
                break
        parts.append(line if cut is None else line[:cut])
        if cut is not None or depth == 0:
            break
    return re.sub(r"\s+", " ", " ".join(parts)).strip().rstrip(",")


def index_file(path: Path) -> list[str]:
    lines = path.read_text(encoding="utf-8").splitlines()
    rows, prev_annot = [], ""
    for n, raw in enumerate(lines):
        stripped = raw.strip()
        if stripped.startswith("@"):
            prev_annot = (prev_annot + " " + stripped.split("(")[0]).strip()
            continue
        m = DECL.match(raw)
        if m and len(m.group("indent").expandtabs(4)) <= MAX_INDENT:
            # Member vals/vars are noisy; keep only top-level and class-level
            # properties that look like state or public API.
            kind = m.group("kind")
            indent = len(m.group("indent").expandtabs(4))
            if kind in ("val", "var") and indent > 4:
                prev_annot = ""
                continue
            sig = signature(lines, n)
            if "@Composable" in prev_annot:
                sig = "@Composable " + sig
            rows.append(f"| {n + 1} | {'  ' * (indent // 4)}`{sig}` |")
        if stripped:
            prev_annot = ""
    return rows


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.md"):
        old.unlink()
    groups: dict[str, list[Path]] = {}
    for f in sorted(SRC.rglob("*.kt")):
        rel = f.relative_to(SRC)
        key = "/".join(rel.parts[:2]) if len(rel.parts) > 2 else (rel.parts[0] if len(rel.parts) > 1 else "root")
        groups.setdefault(key, []).append(f)

    toc = ["# Code index", "", "Generated by `scripts/gen_code_index.py`; do not edit by hand.",
           f"Paths are relative to `{SRC.relative_to(ROOT).as_posix()}/`.", "",
           "| Area | Index file | Files |", "|---|---|---|"]
    for key, files in groups.items():
        name = key.replace("/", "-") + ".md"
        body = [f"# {key}", "", f"Source root: `{SRC.relative_to(ROOT).as_posix()}/`", ""]
        for f in files:
            rel = f.relative_to(SRC).as_posix()
            body += [f"## {rel}", "", "| Line | Declaration |", "|---|---|", *index_file(f), ""]
        (OUT / name).write_text("\n".join(body), encoding="utf-8")
        toc.append(f"| {key} | [{name}]({name}) | {len(files)} |")
    (OUT / "README.md").write_text("\n".join(toc) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
